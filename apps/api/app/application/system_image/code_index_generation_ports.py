from typing import Protocol

from ...domain.system_image.code_index_generation import CodeIndexGenerationPin, CodeIndexLease
from ...domain.system_image.code_provider_protocol import CodeProviderContractReceipt
from .system_image_models import RawAssetRecord


class CodeIndexGenerationPort(Protocol):
    def register(self, source: RawAssetRecord, *, invocation_id: str,
                 snapshot_hash: str, provider_fingerprint: str) -> CodeIndexGenerationPin: ...
    def get(self, project_id: str, generation_id: str) -> CodeIndexGenerationPin: ...
    def source(self, pin: CodeIndexGenerationPin) -> RawAssetRecord: ...
    def claim(self, pin: CodeIndexGenerationPin, *, owner_id: str) -> CodeIndexLease: ...
    def check(self, lease: CodeIndexLease) -> None: ...
    def mark_prepared(self, lease: CodeIndexLease, *, state: str) -> None: ...
    def record_protocol(self, lease: CodeIndexLease, receipt: CodeProviderContractReceipt) -> None: ...
    def record_projection(self, lease: CodeIndexLease, *, projection_hash: str,
                          provider_version: str, entity_count: int, relationship_count: int) -> None: ...
    def release(self, lease: CodeIndexLease, *, failed: bool = False) -> bool: ...
    def request_cancel(self, pin: CodeIndexGenerationPin) -> None: ...
