from __future__ import annotations

from typing import Protocol

from ..platform.account_models import UserProfile
from ...domain.system_image.structure_work import StructureWorkLease
from .structure_builds import StructureBuildInput


class StructureJobWorkflowPort(Protocol):
    enabled: bool

    async def start(self, invocation_id: str) -> bool: ...


class StructureJobRepositoryPort(Protocol):
    def register(self, request: StructureBuildInput, invocation_id: str, actor_id: str) -> None: ...
    def command(self, invocation_id: str) -> tuple[StructureBuildInput, str]: ...
    def execution(self, invocation_id: str) -> UserProfile: ...
    def claim(self, invocation_id: str, owner_id: str) -> StructureWorkLease: ...
    def require_lease(self, lease: StructureWorkLease, actor: UserProfile) -> None: ...
    def renew(self, lease: StructureWorkLease) -> None: ...
    def release(self, lease: StructureWorkLease) -> None: ...
    def finish(self, invocation_id: str, status: str, *, lease: StructureWorkLease | None = None) -> str: ...
    def pending(self, *, after_id: str = "", limit: int = 100) -> list[tuple[str, str]]: ...
