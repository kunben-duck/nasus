"""Trusted integration seams, deliberately not exposed as model tool inputs.

The target registry is operator-owned. A target must enforce the lease generation
and deadline at the resource, including delayed work, and keep writers fenced
after stop_and_fence. A database row lock alone cannot fence a remote process.
No default dump/reset implementation exists. Verification flags must come from
actual adapter checks, not command acceptance or a successful object upload.
Before admission requires an actually clean, stopped source and an independently
restored before snapshot. After capture follows execution cessation. Both restores
must leave the source untouched; reset_to_clean_baseline is a separate source
operation, not a substitute for either independent-copy restore. Copy targets and
their isolation must be chosen and proved by the adapter, never by model inputs.
"""
from __future__ import annotations

from typing import Protocol

from ...domain.quality_loop.execution_environment_lifecycle import (
    BaselineResetVerification, CleanBaselineVerification, EnvironmentLease, ExecutionStoppedProof,
    IndependentRestoreVerification, RegisteredExecutionEnvironment, SnapshotVerification, StoredExecutionSnapshot,
)


class EnvironmentLifecycleAccessPort(Protocol):
    def require_access(self, *, project_id: str, version_id: str, batch_id: str) -> None: ...


class EnvironmentLifecycleRepositoryPort(Protocol):
    def register(self, environment: RegisteredExecutionEnvironment) -> None: ...
    def acquire(self, *, environment_id: str, project_id: str, version_id: str,
                batch_id: str, owner_id: str, ttl_seconds: int) -> EnvironmentLease: ...
    def require_live(self, lease: EnvironmentLease, *, phases: tuple[str, ...]) -> None: ...
    def transition(self, lease: EnvironmentLease, *, expected: tuple[str, ...], phase: str,
                   stopped: ExecutionStoppedProof | None = None) -> None: ...
    def record_baseline(self, lease: EnvironmentLease, proof: CleanBaselineVerification) -> None: ...
    def record_snapshot(self, lease: EnvironmentLease, snapshot: StoredExecutionSnapshot) -> None: ...
    def snapshot(self, lease: EnvironmentLease, phase: str) -> StoredExecutionSnapshot: ...
    def record_independent_restore(self, lease: EnvironmentLease, proof: IndependentRestoreVerification) -> None: ...
    def restore_verification(self, lease: EnvironmentLease, phase: str) -> IndependentRestoreVerification: ...
    def record_reset(self, lease: EnvironmentLease, proof: BaselineResetVerification) -> None: ...
    def release(self, lease: EnvironmentLease) -> None: ...
    def quarantine(self, lease: EnvironmentLease, *, reason: str) -> None: ...
    def reap_expired(self, environment_id: str) -> bool: ...


class ExecutionSnapshotStorePort(Protocol):
    def archive(self, lease: EnvironmentLease, snapshot_id: str, phase: str, body: bytes) -> StoredExecutionSnapshot: ...
    def read_verified(self, lease: EnvironmentLease, snapshot: StoredExecutionSnapshot) -> bytes: ...


class ControlledSnapshotTargetPort(Protocol):
    def stop_and_fence(self, lease: EnvironmentLease) -> ExecutionStoppedProof: ...
    def verify_clean_baseline(self, lease: EnvironmentLease, stopped: ExecutionStoppedProof) -> CleanBaselineVerification: ...
    def capture(self, lease: EnvironmentLease, stopped: ExecutionStoppedProof, *, max_bytes: int) -> bytes: ...
    def verify_snapshot(self, lease: EnvironmentLease, snapshot_id: str, phase: str, body: bytes) -> SnapshotVerification: ...
    def restore_to_independent_copy(self, lease: EnvironmentLease, snapshot: StoredExecutionSnapshot,
                                    body: bytes) -> IndependentRestoreVerification: ...
    def reset_to_clean_baseline(self, lease: EnvironmentLease, before: StoredExecutionSnapshot,
                                after: StoredExecutionSnapshot, before_body: bytes,
                                stopped: ExecutionStoppedProof) -> BaselineResetVerification: ...


class ControlledSnapshotTargetsPort(Protocol):
    def resolve(self, target_key: str) -> ControlledSnapshotTargetPort: ...
