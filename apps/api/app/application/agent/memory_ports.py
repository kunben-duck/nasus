from __future__ import annotations

from typing import Protocol, Any

from .memory_models import ConversationDigest


class ConversationSummaryModelPort(Protocol):
    def binding(self) -> dict[str, Any]: ...
    def counter(self): ...
    def budget(self): ...
    async def summarize(self, payload: dict, binding: dict) -> tuple[ConversationDigest, dict]: ...


class ConversationMemoryJobPort(Protocol):
    def enqueue(self, job: dict) -> dict: ...
    def get(self, job_id: str) -> dict: ...
    def latest(self, conversation_id: str) -> dict | None: ...
    def pending(self) -> list[str]: ...
    def claim(self, job_id: str) -> dict | None: ...
    def fail(self, job_id: str, reason: str, attempt: int) -> None: ...
    def commit(self, job: dict, checkpoint) -> bool: ...

