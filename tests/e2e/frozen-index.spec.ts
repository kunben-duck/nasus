import { expect, test } from '@playwright/test'
import { mkdirSync, rmSync } from 'node:fs'
import { resolve } from 'node:path'
import { analysisApi, analysisSource, captureAnalysis } from './source-analysis-fixtures'
import { indexBrowserFixture, publishIndexFixture } from './frozen-index-fixtures'

for (const theme of ['light', 'dark']) {
test(`published index consent, model changes, refresh and fail-closed pins (${theme})`, async ({ page, request }) => {
  test.setTimeout(240_000)
  const exweb = process.env.EXWEB_FIXTURE_ROOT, source = exweb ? resolve(exweb) : analysisSource()
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  let state: Awaited<ReturnType<typeof indexBrowserFixture>> | undefined
  try {
    const v = await captureAnalysis(request, source), pin = await publishIndexFixture(request, v)
    state = await indexBrowserFixture(page, v.projectId, pin, (await v.revisions())[0].binding_id)
    expect((await request.patch(`${analysisApi}/v1/settings`, { headers: v.owner.headers, data: { theme } })).ok()).toBeTruthy()
    await page.addInitScript((token) => { localStorage.setItem('nasus_api_token', token); localStorage.setItem('nasus.locale', 'en') }, v.owner.token)
    await page.goto(`/projects/${v.projectId}/knowledge`)
    const panel = page.getByRole('region', { name: 'Published retrieval index', exact: true })
    await expect(panel.getByRole('combobox')).toHaveCount(0)
    await panel.getByRole('button', { name: 'Inspect retrieval index', exact: true }).click()
    await expect(panel).toContainText('No completed index for this publication.')
    const model = panel.getByRole('combobox', { name: 'Index embedding model', exact: true })
    await expect(model.locator('option')).toHaveCount(3)
    const prepare = panel.getByRole('button', { name: 'Preview index egress', exact: true })
    await expect(prepare).toBeDisabled()
    await model.selectOption('embedding-A')
    await prepare.click()
    await expect(panel.getByTestId('frozen-index-preview')).toContainText('https://embedding.example/v1')
    expect(state.writes).toBe(0)
    const build = panel.getByRole('button', { name: 'Build confirmed index', exact: true })
    const consent = panel.getByRole('checkbox', { name: 'I authorize these exact source bytes, model destination and subsequent retrieval queries.', exact: true })
    await expect(build).toBeDisabled()
    await consent.check()
    await expect(build).toBeEnabled()
    await model.selectOption('embedding-B')
    await expect(panel.getByTestId('frozen-index-preview')).toHaveCount(0)
    await prepare.click()
    await consent.check()
    await panel.getByRole('button', { name: 'Reload index status', exact: true }).click()
    await expect(panel.getByTestId('frozen-index-preview')).toHaveCount(0)
    await prepare.click()
    await consent.check()
    await page.setViewportSize({ width: 390, height: 844 })
    await panel.getByTestId('frozen-index-preview').scrollIntoViewIfNeeded()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBe(true)
    const selectBox = await model.boundingBox(), panelBox = await panel.boundingBox()
    expect(selectBox && panelBox && selectBox.x + selectBox.width <= panelBox.x + panelBox.width).toBeTruthy()
    await expect(build).toHaveCSS('border-radius', '9px')
    await expect(build).toHaveCSS('border-top-width', '1px')
    mkdirSync(resolve('output/playwright'), { recursive: true })
    await page.screenshot({ path: resolve(`output/playwright/frozen-index-${theme}-mobile.png`) })
    await build.click()
    await expect.poll(() => state!.confirmations).toBe(1)
    await expect(build).toBeDisabled()
    await expect(model).toBeDisabled()
    expect(state.writes).toBe(1)
    state.release()
    await expect(panel.getByTestId('frozen-index-state')).toHaveText('Index ready for this publication')
    await page.reload()
    await panel.getByRole('button', { name: 'Inspect retrieval index', exact: true }).click()
    await expect(panel.getByTestId('frozen-index-state')).toHaveText('Index ready for this publication')
    expect(state.writes).toBe(1)
    const queryButton = panel.getByRole('button', { name: 'Preview AC query budget', exact: true })
    const queryPlan = panel.getByTestId('context-retrieval-plan')
    expect(state.queryPlans).toBe(0)
    await queryButton.click()
    await expect(queryPlan).toContainText('2 AC queries')
    await expect(queryPlan).toContainText('No queries were sent')
    expect(state.queryPlans).toBe(1)
    expect(state.writes).toBe(1)
    const execute = panel.getByRole('region', { name: 'Execute AC context retrieval', exact: true })
    const retrieve = execute.getByRole('button', { name: 'Retrieve confirmed AC context', exact: true })
    const authorize = execute.getByRole('checkbox')
    await expect(retrieve).toBeDisabled()
    await authorize.check()
    await retrieve.click()
    await expect.poll(() => state.queryConfirmations).toBe(1)
    expect(state.queryWrites).toBe(1)
    await expect(execute.getByRole('button', { name: 'Cancel context retrieval', exact: true })).toBeVisible()
    await page.reload()
    await panel.getByRole('button', { name: 'Inspect retrieval index', exact: true }).click()
    await queryButton.click()
    await expect(execute.getByRole('button', { name: 'Cancel context retrieval', exact: true })).toBeVisible()
    await expect(retrieve).toBeDisabled()
    await execute.getByRole('button', { name: 'Cancel context retrieval', exact: true }).click()
    await expect(execute).toContainText('Retrieval stopped without a complete mapping')
    await queryButton.click()
    await authorize.check()
    await retrieve.click()
    await expect.poll(() => state.queryConfirmations).toBe(2)
    state.queryStatus = 'completed'
    await expect(execute.getByTestId('context-retrieval-result')).toContainText('2 AC retrievals committed')
    await execute.getByRole('button', { name: 'Inspect published context', exact: true }).click()
    const contextRequest = page.waitForRequest((request) => request.url().includes('/context-packs/preview?'))
    await page.route(`**/projects/${v.projectId}/system-image/context-packs/preview?**`, (route) => route.fulfill({ status: 403,
      json: { error: { code: 'source_access_denied', message: 'Explicit context boundary fixture' } } }))
    await execute.getByRole('button', { name: 'Preview context', exact: true }).click()
    const params = new URL((await contextRequest).url()).searchParams
    expect(params.get('policy_revision')).toBe('nasus.test-design-context.v5')
    expect(JSON.parse(params.get('retrieval_bindings')!)).toEqual({ 'fixture-ac-0': 'fixture-trace-0', 'fixture-ac-1': 'fixture-trace-1' })
    await expect(panel).toContainText('Published context could not be verified')
    await queryButton.click()
    state.corruptQueryResult = true
    await expect(execute).toContainText('Completed retrieval could not be verified')
    await expect(execute.getByTestId('context-retrieval-result')).toHaveCount(0)
    state.corruptQueryResult = false
    await queryButton.click()
    await expect(execute.getByTestId('context-retrieval-result')).toBeVisible()
    await queryPlan.scrollIntoViewIfNeeded()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBe(true)
    await expect(queryButton).toHaveCSS('border-radius', '9px')
    await page.screenshot({ path: resolve(`output/playwright/context-query-plan-${theme}-mobile.png`) })
    for (const invalid of ['scope', 'budget', 'authority']) {
      state.corruptPlan = invalid
      await queryButton.click()
      await expect(panel.getByRole('alert')).toContainText('Query plan could not be verified.')
      await expect(queryPlan).toHaveCount(0)
    }
    state.corruptPlan = ''
    state.queryCount = 0
    await queryButton.click()
    await expect(queryPlan).toContainText('No source ACs in this publication.')
    state.holdPlan = true
    await queryButton.click()
    await expect(queryButton).toBeDisabled()
    await panel.getByRole('button', { name: 'Reload index status', exact: true }).click()
    await expect(panel.getByTestId('frozen-index-state')).toHaveText('Index ready for this publication')
    state.releasePlan()
    await expect(queryPlan).toHaveCount(0)
    state.changedModel = true
    await panel.getByRole('button', { name: 'Reload index status', exact: true }).click()
    await expect(panel).toContainText('Model configuration changed. A new preview and confirmed build are required.')
    await expect(queryButton).toHaveCount(0)
    await model.selectOption('embedding-A')
    state.corruptPreview = true
    await prepare.click()
    await expect(panel.getByRole('alert')).toContainText('Index preview could not be verified.')
    await expect(build).toHaveCount(0)
    state.corruptPreview = false
    await prepare.click()
    await consent.check()
    state.fail = true
    await build.click()
    await expect.poll(() => state!.confirmations).toBe(2)
    state.release()
    await expect(panel.getByRole('alert')).toContainText('No automatic retry was sent.')
    await expect(build).toBeDisabled()
    expect(state.writes).toBe(2)
    state.corruptStatus = true
    await panel.getByRole('button', { name: 'Reload index status', exact: true }).click()
    await expect(panel.getByRole('alert')).toContainText('Index scope could not be verified.')
    await expect(model).toHaveCount(0)
    await expect(panel.getByTestId('frozen-index-preview')).toHaveCount(0)
    await expect(panel.getByTestId('frozen-index-state')).toHaveCount(0)
    expect(errors).toEqual([])
  } finally { state?.release(); state?.releasePlan(); if (!exweb) rmSync(source, { recursive: true, force: true }) }
})
}
