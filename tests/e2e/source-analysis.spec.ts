test('failed parsing is inspectable without replacing a successful historical report', async ({ page, request }) => {
  const source = analysisSource()
  try {
    const fixture = await captureAnalysis(request, source)
    writeFileSync(join(source, 'Broken.java'), 'class Broken { void incomplete(\n')
    await fixture.invoke('system_image.sources.ingest')
    await fixture.invoke('system_image.context.materialize', {}, 'failed')
    const failed = (await fixture.revisions()).find((item) => item.source_revision_id !== fixture.revision)!
    await openAnalysis(page, fixture.projectId, fixture.owner.token)
    const dialog = await selectAnalysis(page, failed.source_revision_id)
    await dialog.getByRole('combobox', { name: 'Parser status', exact: true }).selectOption('failed')
    const list = dialog.getByRole('list', { name: 'Analysis observations' })
    await expect(list.locator(':scope > li')).toHaveCount(1)
    await expect(list).toContainText('Broken.java')
    await expect(list).toContainText('Syntax errors prevented registration.')
    const reportSelector = dialog.getByRole('combobox', { name: 'Analysis report', exact: true })
    const selectedReport = await reportSelector.inputValue()
    expect(selectedReport).not.toBe('')
    let releaseRead!: () => void
    const heldRead = new Promise<void>((resolve) => { releaseRead = resolve })
    const revisionPath = `/projects/${fixture.projectId}/system-image/code-source-revisions`
    await page.route((url) => url.pathname.endsWith(revisionPath), async (route) => {
      await heldRead
      await route.continue()
    }, { times: 1 })
    const checking = page.waitForRequest((req) => new URL(req.url()).pathname.endsWith(revisionPath))
    const checked = page.waitForResponse((response) => new URL(response.url()).pathname.endsWith(revisionPath))
    try {
      await page.evaluate(() => window.dispatchEvent(new Event('visibilitychange')))
      await checking
      await expect(list).not.toBeVisible()
    } finally { releaseRead() }
    expect((await checked).ok()).toBeTruthy()
    await expect(reportSelector).toHaveValue(selectedReport)
    await expect(list).toBeVisible()
    await expect(list).toContainText('Broken.java')
    await selectAnalysis(page, fixture.revision)
    await expect(dialog).toContainText('27 matching observations')
    await expect(list).not.toContainText('Broken.java')
    await page.keyboard.press('Escape')
    const other = await request.post(`${analysisApi}/v1/projects`, {
      headers: fixture.owner.headers, data: { name: 'Empty analysis scope' },
    })
    expect(other.ok()).toBeTruthy()
    const otherId = (await other.json()).id
    await page.goto(`/projects/${otherId}/knowledge`)
    await expect(dialog).toHaveCount(0)
    await page.getByRole('button', { name: 'Source analyses', exact: true }).click()
    await expect(dialog).toContainText('No captured code revisions are available to you.')
    await expect(dialog.getByRole('combobox', { name: 'Captured code revision', exact: true }).locator('option')).toHaveCount(1)
    await expect(list).toHaveCount(0)
    await expect(dialog).not.toContainText(fixture.revision)
    await page.goto(`/projects/${fixture.projectId}/knowledge`)
    await expect(dialog).toHaveCount(0)
    await page.getByRole('button', { name: 'Source analyses', exact: true }).click()
    await expect(dialog.getByRole('combobox', { name: 'Captured code revision', exact: true })).toHaveValue('')
    await expect(list).toHaveCount(0)
  } finally { rmSync(source, { recursive: true, force: true }) }
})

for (const revoke of ['source', 'project']) {
  test(`${revoke} revocation denies the real report request and clears old content`, async ({ page, request }) => {
    const source = analysisSource()
    try {
      const { owner, projectId, revision } = await captureAnalysis(request, source)
      const viewer = await analysisAccount(request)
      const memberUrl = `${analysisApi}/v1/projects/${projectId}/members/${viewer.userId}`
      expect((await request.put(memberUrl, { headers: owner.headers, data: { role: 'viewer' } })).ok()).toBeTruthy()
      if (revoke === 'source') analysisSourcePolicy(projectId, [viewer.userId])
      await openAnalysis(page, projectId, viewer.token)
      const dialog = await selectAnalysis(page, revision)
      let denied: number | null = null
      await page.route((url) => url.pathname.includes(`/projects/${projectId}/system-image/source-analyses/`)
        && url.searchParams.get('offset') === '25', async (route) => {
        if (revoke === 'source') analysisSourcePolicy(projectId, [])
        else expect((await request.delete(memberUrl, { headers: owner.headers })).ok()).toBeTruthy()
        const response = await route.fetch()
        denied = response.status()
        await route.fulfill({ response })
      }, { times: 1 })
      await dialog.getByRole('button', { name: 'Next page', exact: true }).click()
      await expect.poll(() => denied).toBe(403)
      await expect(page.getByRole('alert').filter({ hasText: /Source analysis could not be verified|System image could not be verified/ })).toBeVisible()
      await expect(page.getByRole('list', { name: 'Analysis observations' })).toHaveCount(0)
      if (revoke === 'source') {
        await expect(dialog.getByRole('combobox', { name: 'Captured code revision', exact: true })).toHaveCount(0)
        analysisSourcePolicy(projectId, [viewer.userId])
        await page.context().setOffline(true)
        await page.context().setOffline(false)
        await expect(page.getByRole('list', { name: 'Analysis observations' })).toHaveCount(0)
        await dialog.getByRole('button', { name: 'Reload analyses', exact: true }).click()
        await expect(dialog.getByRole('combobox', { name: 'Captured code revision', exact: true })).toHaveValue('')
        await expect(dialog.getByRole('combobox', { name: 'Analysis report', exact: true })).toHaveCount(0)
      }
    } finally { rmSync(source, { recursive: true, force: true }) }
  })
}
